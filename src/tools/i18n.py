"""
Tiny translation toolchain (no gettext install needed).

    python tools/i18n.py extract   # list every translatable string in the code
    python tools/i18n.py build     # check German coverage, write django.po + django.mo

German texts live in tools/german.py (a plain dict: English -> German).
Run `build` after changing any template or text; commit the generated files in
config/locale/de/LC_MESSAGES/.
"""

import ast
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALE_DIR = ROOT / "config" / "locale" / "de" / "LC_MESSAGES"

TRANS_TAG = re.compile(r"""\{%\s*trans\s+(?:"((?:[^"\\]|\\.)*)"|'((?:[^'\\]|\\.)*)')""")
BLOCKTRANS = re.compile(
    r"\{%\s*blocktrans(?:late)?\b[^%]*%\}(.*?)\{%\s*endblocktrans(?:late)?\s*%\}", re.S
)
VAR = re.compile(r"\{\{\s*(\w+)\s*\}\}")
PY_CALL = re.compile(r"\b(?:_|gettext|gettext_lazy|ngettext)$")


def unescape(s):
    return s.replace('\\"', '"').replace("\\'", "'")


def template_strings(path):
    text = path.read_text(encoding="utf-8")
    found = []
    for m in TRANS_TAG.finditer(text):
        found.append(unescape(m.group(1) if m.group(1) is not None else m.group(2)))
    for m in BLOCKTRANS.finditer(text):
        body = " ".join(m.group(1).split())
        found.append(VAR.sub(lambda v: f"%({v.group(1)})s", body))
    return found


def python_strings(path):
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except SyntaxError:
        return []
    found = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and node.args:
            func = node.func
            name = func.id if isinstance(func, ast.Name) else getattr(func, "attr", "")
            if PY_CALL.search(name) and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                found.append(node.args[0].value)
    return found


def collect():
    strings = {}
    skip = {"migrations", "tools", "node_modules", "__pycache__", "static", "blocks.py", "seed_site.py", "seed_demo.py"}
    for path in sorted(ROOT.rglob("*")):
        if any(part in skip for part in path.parts) or path.name in skip:
            continue
        if path.suffix == ".html":
            items = template_strings(path)
        elif path.suffix == ".txt":
            items = template_strings(path)
        elif path.suffix == ".py":
            items = python_strings(path)
        else:
            continue
        for s in items:
            if s.strip():
                strings.setdefault(s, path.relative_to(ROOT).as_posix())
    return strings


# --- .po / .mo writers ------------------------------------------------------


def po_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_po(path, entries):
    lines = [
        '# German translation for Johanna Lackner\'s site (generated by tools/i18n.py).',
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: johanna-art-site\\n"',
        '"Language: de\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"',
        "",
    ]
    for msgid, msgstr in sorted(entries.items()):
        lines.append(f'msgid "{po_escape(msgid)}"')
        lines.append(f'msgstr "{po_escape(msgstr)}"')
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def write_mo(path, entries):
    header = (
        "Project-Id-Version: johanna-art-site\n"
        "Language: de\n"
        "MIME-Version: 1.0\n"
        "Content-Type: text/plain; charset=UTF-8\n"
        "Content-Transfer-Encoding: 8bit\n"
        "Plural-Forms: nplurals=2; plural=(n != 1);\n"
    )
    messages = {"": header}
    messages.update(entries)
    keys = sorted(messages)
    ids = b""
    strs = b""
    offsets = []
    for k in keys:
        kb = k.encode("utf-8")
        vb = messages[k].encode("utf-8")
        offsets.append((len(ids), len(kb), len(strs), len(vb)))
        ids += kb + b"\0"
        strs += vb + b"\0"
    n = len(keys)
    keystart = 7 * 4 + 16 * n
    valuestart = keystart + len(ids)
    koffsets = []
    voffsets = []
    for o1, l1, o2, l2 in offsets:
        koffsets += [l1, o1 + keystart]
        voffsets += [l2, o2 + valuestart]
    output = struct.pack("Iiiiiii", 0x950412DE, 0, n, 7 * 4, 7 * 4 + n * 8, 0, 0)
    output += struct.pack(f"{len(koffsets)}i", *koffsets)
    output += struct.pack(f"{len(voffsets)}i", *voffsets)
    output += ids + strs
    path.write_bytes(output)


def main():
    command = sys.argv[1] if len(sys.argv) > 1 else "build"
    strings = collect()

    if command == "extract":
        for s, where in sorted(strings.items()):
            print(f"{where}: {s}")
        print(f"\n{len(strings)} strings", file=sys.stderr)
        return

    sys.path.insert(0, str(Path(__file__).parent))
    from german import GERMAN

    missing = [s for s in strings if s not in GERMAN]
    unused = [s for s in GERMAN if s not in strings]
    if missing:
        print("MISSING German translations:")
        for s in missing:
            print(f"  [{strings[s]}] {s!r}")
    if unused:
        print(f"({len(unused)} entries in german.py are no longer used)")

    LOCALE_DIR.mkdir(parents=True, exist_ok=True)
    entries = {k: v for k, v in GERMAN.items() if v}
    write_po(LOCALE_DIR / "django.po", entries)
    write_mo(LOCALE_DIR / "django.mo", entries)
    print(f"{len(strings)} strings found, {len(strings) - len(missing)} translated -> {LOCALE_DIR}")
    if missing:
        sys.exit(1)


if __name__ == "__main__":
    main()
